#!/usr/bin/env python3
"""
Build categorized .swibank files for reMID.lv2 direct SID-Wizard playback.

This repo no longer uses the reMID ".conf instrument language" at runtime.
Instead, the LV2 plugin loads a .swibank mapping file that selects which
SID-Wizard .swi instrument to run for each MIDI Program Change.

Outputs:
  instruments/banks/bank-<id>-<page>.swibank
  instruments/banks/banks_index.json
  instruments/banks/drumkit-gm.swibank (small GM-style example)
"""

from __future__ import annotations

from dataclasses import dataclass
from fnmatch import fnmatch
from pathlib import Path
from typing import Dict, List
import argparse
import json


@dataclass(frozen=True)
class BankDef:
    id: str
    label: str
    patterns: list[str]


def load_rules(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def classify(filename: str, rules: dict) -> str:
    fn = filename.lower()
    for bank in rules.get("banks", []):
        for pat in bank.get("patterns", []):
            if fnmatch(fn, pat.lower()):
                return bank["id"]
    return rules.get("fallback_bank", {}).get("id", "misc")


def write_swibank(path: Path, name: str, base_dir: str, program_to_file: Dict[int, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = []
    lines.append("# generated by converter/build_banks.py")
    lines.append("")
    lines.append("[meta]")
    lines.append(f"name={name}")
    lines.append(f"base={base_dir}")
    lines.append("")
    lines.append("[programs]")
    for p in sorted(program_to_file.keys()):
        lines.append(f"{p}={program_to_file[p]}")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def write_gm_drumkit(path: Path, base_dir: str) -> None:
    """
    Minimal example drumkit mapping. Feel free to customize.
    """
    lines: list[str] = []
    lines.append("# generated by converter/build_banks.py")
