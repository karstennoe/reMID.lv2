    lines.append("39=clap-snare.swi")     # Clap
    lines.append("45=tom-containr.swi")   # Tom
    lines.append("41=tom-filtkbtr.swi")   # Low tom
    lines.append("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")

