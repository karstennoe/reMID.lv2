def main() -> int:
    repo_root = Path(__file__).resolve().parent.parent

    ap = argparse.ArgumentParser()
    ap.add_argument("--rules", default=str(repo_root / "converter" / "bank_rules.json"))
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    rules = load_rules(Path(args.rules))
    input_dir = (repo_root / rules.get("input_dir", "converter/sidwizard_instruments")).resolve()
    output_dir = (repo_root / rules.get("output_dir", "instruments/banks")).resolve()
    base_dir = rules.get("bank_base_dir", "../swi")
    per_file = int(rules.get("max_programs_per_file", 128))

    swis = sorted(input_dir.glob("*.swi"))
    if not swis:
        raise SystemExit(f"No .swi files found in {input_dir}")

    # Group by bank id.
    grouped: Dict[str, List[Path]] = {}
    for p in swis:
        bid = classify(p.name, rules)
        grouped.setdefault(bid, []).append(p)

    # Always provide an "all" bank (paged).
    grouped.setdefault("all", [])
    grouped["all"] = list(swis)

    # Bank label lookup.
    labels: Dict[str, str] = {b["id"]: b.get("label", b["id"]) for b in rules.get("banks", [])}
    labels[rules.get("fallback_bank", {}).get("id", "misc")] = rules.get("fallback_bank", {}).get("label", "Misc")
    labels["all"] = "All"

    index: dict = {"base_dir": base_dir, "banks": {}}

    for bid, files in sorted(grouped.items()):
        pages: List[List[Path]] = [files[i : i + per_file] for i in range(0, len(files), per_file)]
        index["banks"][bid] = []
        for page_i, page in enumerate(pages):
            name = f"{labels.get(bid, bid)} ({page_i})"
            out = output_dir / f"bank-{bid}-{page_i}.swibank"
            mapping = {i: page[i].name for i in range(len(page))}
            if not args.dry_run:
                write_swibank(out, name=name, base_dir=base_dir, program_to_file=mapping)
            index["banks"][bid].append({"file": str(out.relative_to(repo_root)).replace('\\\\', '/'), "name": name, "programs": mapping})

    # Always emit a small GM drumkit example.
    dk_path = output_dir / "drumkit-gm.swibank"
    if not args.dry_run:
        write_gm_drumkit(dk_path, base_dir=base_dir)
    index["drumkit_gm"] = str(dk_path.relative_to(repo_root)).replace('\\\\', '/')

    # Curated "built-in" drumkit.
    dk2_path = output_dir / "drumkit-remid.swibank"
    if not args.dry_run:
        write_builtin_drumkit(dk2_path, base_dir=base_dir)
    index["drumkit_remid"] = str(dk2_path.relative_to(repo_root)).replace('\\\\', '/')

    idx_path = output_dir / "banks_index.json"
    if not args.dry_run:
        idx_path.write_text(json.dumps(index, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    # Also write a copy into modgui/ so the MOD GUI can load it via its own resourcesDirectory.
    modgui_idx = repo_root / "modgui" / "banks_index.json"
    if not args.dry_run:
        modgui_idx.parent.mkdir(parents=True, exist_ok=True)
        modgui_idx.write_text(json.dumps(index, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    print(f"Input:  {input_dir}")
    print(f"Output: {output_dir}")
    print(f"Wrote:  {idx_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
